const storePageTitles = {
  ru: "Kinoxona Store — предварительный каталог",
  en: "Kinoxona Store — pilot catalogue",
  uz: "Kinoxona Store — sinov katalogi"
};

const savedStoreLanguage = localStorage.getItem("kinoxona-language");
let storeLanguage = Object.hasOwn(storeTranslations, savedStoreLanguage) ? savedStoreLanguage : "ru";

const storeHeader = document.querySelector("[data-header]");
const storeMenuToggle = document.querySelector(".menu-toggle");
const storeNav = document.querySelector(".main-nav");

function setStoreLanguage(language) {
  storeLanguage = language;
  localStorage.setItem("kinoxona-language", language);
  document.documentElement.lang = language;
  document.title = storePageTitles[language];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = storeTranslations[language][element.dataset.i18n];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = storeTranslations[language][element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setStoreLanguage(button.dataset.lang));
});

storeMenuToggle?.addEventListener("click", () => {
  const isOpen = storeMenuToggle.getAttribute("aria-expanded") === "true";
  storeMenuToggle.setAttribute("aria-expanded", String(!isOpen));
  storeNav.classList.toggle("is-open", !isOpen);
  document.body.classList.toggle("menu-open", !isOpen);
});

storeNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    storeMenuToggle?.setAttribute("aria-expanded", "false");
    storeNav.classList.remove("is-open");
    document.body.classList.remove("menu-open");
  });
});

window.addEventListener("scroll", () => {
  storeHeader?.classList.toggle("is-scrolled", window.scrollY > 40);
}, { passive: true });

const storeObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("is-visible");
      storeObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.1 });

document.querySelectorAll(".reveal").forEach((element) => storeObserver.observe(element));
document.querySelector("#year").textContent = new Date().getFullYear();

document.querySelectorAll("[data-product]").forEach((card) => {
  const productId = card.dataset.product;
  const productUrl = `product.html?id=${encodeURIComponent(productId)}&from=store`;
  const visual = card.querySelector(".product-visual");
  const openLabel = document.createElement("span");
  openLabel.className = "product-open";
  openLabel.dataset.i18n = "viewProduct";
  visual?.append(openLabel);

  card.classList.add("product-card-clickable");
  card.id = `product-${productId}`;
  card.setAttribute("role", "link");
  card.setAttribute("tabindex", "0");

  const openProduct = () => {
    sessionStorage.setItem("kinoxona-store-return", JSON.stringify({
      productId,
      scrollY: window.scrollY
    }));
    window.location.href = productUrl;
  };
  card.addEventListener("click", openProduct);
  card.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      openProduct();
    }
  });
});

setStoreLanguage(storeLanguage);

function restoreStorePosition() {
  const returnFromQuery = new URLSearchParams(window.location.search).get("return");
  const returnFromHistory = sessionStorage.getItem("kinoxona-store-restore");
  const productToRestore = returnFromQuery || returnFromHistory;
  if (!productToRestore) return;

  let storedState = null;
  try {
    storedState = JSON.parse(sessionStorage.getItem("kinoxona-store-return") || "null");
  } catch {
    storedState = null;
  }

  const targetCard = document.querySelector(`[data-product="${CSS.escape(productToRestore)}"]`);
  const restore = () => {
    if (storedState?.productId === productToRestore && Number.isFinite(storedState.scrollY)) {
      window.scrollTo(0, storedState.scrollY);
    } else {
      targetCard?.scrollIntoView({ block: "center" });
    }
  };

  requestAnimationFrame(() => requestAnimationFrame(restore));
  window.setTimeout(restore, 180);
  sessionStorage.removeItem("kinoxona-store-restore");

  if (returnFromQuery) {
    const cleanUrl = new URL(window.location.href);
    cleanUrl.searchParams.delete("return");
    window.history.replaceState(null, "", `${cleanUrl.pathname}${cleanUrl.search}${cleanUrl.hash}`);
  }
}

window.addEventListener("pageshow", restoreStorePosition);
