const storePageTitles = {
  ru: "Kinoxona Store — предварительный каталог",
  en: "Kinoxona Store — pilot catalogue",
  uz: "Kinoxona Store — sinov katalogi"
};

const savedStoreLanguage = localStorage.getItem("kinoxona-language");
let storeLanguage = Object.hasOwn(storeTranslations, savedStoreLanguage) ? savedStoreLanguage : "ru";

const storeHeader = document.querySelector("[data-header]");
const storeMenuToggle = document.querySelector(".menu-toggle");
const storeNav = document.querySelector(".main-nav");

function setStoreLanguage(language) {
  storeLanguage = language;
  localStorage.setItem("kinoxona-language", language);
  document.documentElement.lang = language;
  document.title = storePageTitles[language];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = storeTranslations[language][element.dataset.i18n];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = storeTranslations[language][element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setStoreLanguage(button.dataset.lang));
});

storeMenuToggle?.addEventListener("click", () => {
  const isOpen = storeMenuToggle.getAttribute("aria-expanded") === "true";
  storeMenuToggle.setAttribute("aria-expanded", String(!isOpen));
  storeNav.classList.toggle("is-open", !isOpen);
  document.body.classList.toggle("menu-open", !isOpen);
});

storeNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    storeMenuToggle?.setAttribute("aria-expanded", "false");
    storeNav.classList.remove("is-open");
    document.body.classList.remove("menu-open");
  });
});

window.addEventListener("scroll", () => {
  storeHeader?.classList.toggle("is-scrolled", window.scrollY > 40);
}, { passive: true });

const storeObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("is-visible");
      storeObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.1 });

document.querySelectorAll(".reveal").forEach((element) => storeObserver.observe(element));
document.querySelector("#year").textContent = new Date().getFullYear();
setStoreLanguage(storeLanguage);
