const monthFormat = {
  ru: new Intl.DateTimeFormat("ru-RU", { day: "2-digit", month: "long", year: "numeric" }),
  uz: new Intl.DateTimeFormat("uz-UZ", { day: "2-digit", month: "long", year: "numeric" })
};

let currentLanguage = localStorage.getItem("kinoxona-language") || "ru";
let screenings = [];
let archiveExpanded = false;

const header = document.querySelector("[data-header]");
const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");
const archiveGrid = document.querySelector("#archive-grid");
const archiveToggle = document.querySelector("#archive-toggle");

function setLanguage(language) {
  currentLanguage = language;
  localStorage.setItem("kinoxona-language", language);
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[language][key];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
  });

  document.title = language === "ru"
    ? "Kinoxona — арт-кинотеатр в Ташкенте"
    : "Kinoxona — Toshkentdagi arthouse kinoteatri";

  renderArchive();
}

function getScreeningDescription(screening) {
  const parts = [];
  if (screening.director) parts.push(screening.director);
  if (screening.year) parts.push(screening.year);
  return parts.join(" · ");
}

function renderArchive() {
  if (!archiveGrid || screenings.length === 0) return;

  const visible = archiveExpanded ? screenings : screenings.slice(0, 6);
  archiveGrid.innerHTML = visible.map((screening, index) => {
    const date = monthFormat[currentLanguage].format(new Date(`${screening.date}T12:00:00`));
    const note = screening.notes ? `<span class="card-note">${screening.notes}</span>` : "";

    return `
      <article class="screening-card">
        <div class="card-top">
          <span>${date}</span>
          <span class="card-index">${String(index + 1).padStart(2, "0")}</span>
        </div>
        <div class="card-bottom">
          ${note}
          <h3>${screening.title}</h3>
          <p class="card-meta">${getScreeningDescription(screening)}</p>
        </div>
      </article>
    `;
  }).join("");

  const label = archiveExpanded ? translations[currentLanguage].showLess : translations[currentLanguage].showMore;
  archiveToggle.querySelector("span:first-child").textContent = label;
  archiveToggle.querySelector("span:last-child").textContent = archiveExpanded ? "−" : "＋";
}

async function loadScreenings() {
  try {
    const embeddedData = document.querySelector("#screenings-data");
    let data;

    if (embeddedData) {
      data = JSON.parse(embeddedData.textContent);
    } else {
      const response = await fetch("data/screenings.json");
      if (!response.ok) throw new Error("Screenings could not be loaded");
      data = await response.json();
    }

    screenings = data.screenings.sort((a, b) => b.date.localeCompare(a.date));
    renderArchive();
  } catch (error) {
    console.error(error);
    archiveGrid.innerHTML = "<p>Архив временно недоступен.</p>";
  }
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

archiveToggle?.addEventListener("click", () => {
  archiveExpanded = !archiveExpanded;
  renderArchive();
});

menuToggle?.addEventListener("click", () => {
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isOpen));
  mainNav.classList.toggle("is-open", !isOpen);
  document.body.classList.toggle("menu-open", !isOpen);
});

mainNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    menuToggle?.setAttribute("aria-expanded", "false");
    mainNav.classList.remove("is-open");
    document.body.classList.remove("menu-open");
  });
});

window.addEventListener("scroll", () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 40);
}, { passive: true });

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
document.querySelector("#year").textContent = new Date().getFullYear();

setLanguage(currentLanguage);
loadScreenings();
